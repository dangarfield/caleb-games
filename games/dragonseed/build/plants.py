"""The 82 specimens of the plant shop. All original to this valley.

Row: id, name, binomial, kind, colour, form, petals, leaf, stem, scent, berry,
     mark, habitat, effect, species, start, plate, use

  plate   what the drawing shows. Observable only - this is the matching target.
  use     what it is FOR. Hidden until the plant is named.
  effect  the key behind `use`, so the book can be searched by what a thing does.
  species WHO it is for: "human", "dragon", or "both".

Species is the newest clue and the best one. Morrowfen keeps dragons the way
other places keep dogs, so a third of the counter is veterinary, and a cough in
a dragon is not a cough in a man - it is a different plant on a different shelf.
Ten effects exist for BOTH species as two different plants (ache, burn, cough,
eyes, fever, heart, poisontest, sleep, stomach, wound), which means "something
for a cough" is only half a question until you know who is coughing.

  start   what you begin with, and a POT and a PAGE are separate things.
          Nothing is sold here: a visitor asks and you give. You need the POT to
          have any of it and the PAGE to know what it is.
            "both"  a cutting on the shelf AND an entry in the book
            "pot"   a cutting you cannot name yet - no page to match it to
            "page"  an entry you have read but no cutting - the book says where
                    it grows, which makes an empty page a place to go
            ""      neither, until the story or the map turns it up
          You start with eleven pots and eleven pages and they do not line up.
"""

