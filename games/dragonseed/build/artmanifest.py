# -*- coding: utf-8 -*-
"""Emit js/art.js — what real artwork exists on disk, and where.

    python3 build/artmanifest.py

The game must run with no art at all (every drawing falls back to the generated
SVG plate), with some of it, or with all of it. So nothing hard-codes a
filename: this script looks in art/, and the game asks Art.plant(id) and takes
whatever it gets, including nothing.

Re-run it whenever files are added to or removed from art/.
"""
import os, re, json, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ART  = os.path.join(ROOT, "art")
OUT  = os.path.join(ROOT, "js", "art.js")

# A place the story changes. [last day of this phase, phase name] — the final
# entry's day is ignored, it runs to the end.
PHASES = {
  "moor":   [[5,  "before"],  [99, "after"]],
  "tarn":   [[7,  "full"],    [99, "drained"]],
  "pike":   [[14, "whole"],   [99, "broken"]],
  "barrow": [[10, "closed"],  [99, "opened"]],
}

def scan():
    plant, book, person, loc, story, asset, note = {}, {}, {}, {}, {}, {}, {}
    if not os.path.isdir(ART): return plant, book, person, loc, story, asset, note
    for f in sorted(os.listdir(ART)):
        if not f.endswith(".webp"): continue
        stem = f[:-5]
        m = re.match(r"^plantbook_(n\d+)_", stem)
        if m: book[m.group(1)] = f; continue
        m = re.match(r"^plant_(n\d+)_", stem)
        if m: plant[m.group(1)] = f; continue
        if stem.startswith("person_"): person[stem[7:]] = f; continue
        if stem.startswith("loc_"):    loc[stem[4:]]    = f; continue
        if stem.startswith("story_"):  story[stem[6:]]  = f; continue
        # asset_note_<paperId> is the painted sheet one particular note is
        # written on. It is kept apart from the furniture so the drawer can ask
        # for it by paper id and get nothing back when it has not been drawn.
        m = re.match(r"^asset_note_(p_\w+)$", stem)
        if m: note[m.group(1)] = f; continue
        if stem.startswith("asset_"):  asset[stem[6:]]  = f; continue
    return plant, book, person, loc, story, asset, note

def main():
    plant, book, person, loc, story, asset, note = scan()
    n = sum(len(x) for x in (plant, book, person, loc, story, asset, note))
    j = lambda o: json.dumps(o, ensure_ascii=False, sort_keys=True, indent=1)

    src = '''/* art.js — GENERATED by build/artmanifest.py. Do not edit by hand.
 *
 * The pictures, and only the pictures that actually exist. Everything that
 * draws something asks here first and falls back to the generated SVG plate
 * when the answer is null, so the game runs with all of the art, some of it,
 * or none of it.
 *
 *   Art.plant(id)        the coloured specimen, for the desk, shelf and counter
 *   Art.book(id)         the line-drawn plate, for the book page
 *   Art.person(who)      a customer's face
 *   Art.place(hid, day)  a location, in the state the story has left it in
 *   Art.story(key)       "prologue_0", "evening_07", "ending_end_keep"
 *   Art.asset(id)        a piece of furniture
 *   Art.note(paperId)    the painted sheet that one note is written on
 *   Art.img(url, opts)   an <img> for any of the above
 *   Art.css(url)         the same as a CSS url(), or "none"
 */

const Art = (function () {

  /* Where the pictures are served from. By default the art/ folder sitting next
     to this page, which is what you want locally and what you want on a host
     that serves the whole folder. To put the art somewhere else — a CDN, a
     different Netlify site — set window.DRAGONSEED_ART_BASE (with a trailing
     slash) before this file loads; index.html has the line, commented out.

     Nine background-image rules in css/style.css point at ../art/ directly and
     this does not reach them. Grep for `url("../art/` if the art ever moves. */
  var BASE = (typeof window !== "undefined" && window.DRAGONSEED_ART_BASE) || "art/";

  var PLANT  = %s;
  var BOOK   = %s;
  var PERSON = %s;
  var LOC    = %s;
  var STORY  = %s;
  var ASSET  = %s;
  var NOTE   = %s;

  /* Four places the mother changes on her way through. Each entry is the last
     day that phase is what you would see. */
  var PHASES = %s;

  function url(f) { return f ? BASE + f : null; }

  function place(hid, day) {
    var ph = PHASES[hid];
    if (ph) {
      for (var i = 0; i < ph.length; i++)
        if (day <= ph[i][0] || i === ph.length - 1) {
          var u = url(LOC[hid + "_" + ph[i][1]]);
          if (u) return u;
          break;
        }
    }
    return url(LOC[hid]);
  }

  function esc(s) { return String(s).replace(/[&<>"]/g, function (c) {
    return { "&":"&amp;", "<":"&lt;", ">":"&gt;", '"':"&quot;" }[c]; }); }

  /* Always object-fit: contain, because the art is square or 4:3 and the boxes
     it goes in are neither. Never let a plate be squashed. */
  function img(u, o) {
    if (!u) return "";
    o = o || {};
    return '<img class="art' + (o.cls ? " " + o.cls : "") + '" src="' + esc(u) + '"'
      + (o.w ? ' width="' + o.w + '"' : "")
      + (o.h ? ' height="' + o.h + '"' : "")
      + ' alt="' + esc(o.alt || "") + '" draggable="false"'
      + (o.alt ? "" : ' aria-hidden="true"')
      + ' loading="' + (o.eager ? "eager" : "lazy") + '" decoding="async">';
  }

  function css(u) { return u ? 'url("' + u + '")' : "none"; }

  return {
    plant:  function (id)  { return url(PLANT[id]); },
    book:   function (id)  { return url(BOOK[id]); },
    person: function (who) { return url(PERSON[who]); },
    place:  place,
    story:  function (k)   { return url(STORY[k]); },
    asset:  function (id)  { return url(ASSET[id]); },
    note:   function (id)  { return url(NOTE[id]); },
    img: img, css: css,
    count: %d
  };
})();
''' % (j(plant), j(book), j(person), j(loc), j(story), j(asset), j(note), j(PHASES), n)

    open(OUT, "w", encoding="utf-8").write(src)
    print("wrote js/art.js — %d pictures (%d plants, %d book plates, %d people, "
          "%d location views, %d story panels, %d assets, %d note sheets)"
          % (n, len(plant), len(book), len(person), len(loc), len(story),
             len(asset), len(note)))

if __name__ == "__main__":
    main()
